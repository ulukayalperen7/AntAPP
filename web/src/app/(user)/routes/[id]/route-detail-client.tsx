// ─── Star Rating Widget ───────────────────────────────────────────────────────

function StarRatingWidget({
  routeId,
  onRated
}: {
  routeId: string;
  onRated: (score: number) => void;
}) {
  const [hovered, setHovered] = useState(0);
  const [selected, setSelected] = useState(0);
  const [isSubmitting, startSubmit] = useTransition();
  const [submitted, setSubmitted] = useState(false);
  const handleRate = (score: number) => {
    if (submitted) return;
    setSelected(score);
    startSubmit(async () => {
      try {
        await rateRoute(routeId, score);
        setSubmitted(true);
        onRated(score);
      } catch {
        setSelected(0);
      }
    });
  };
  const active = hovered || selected;
  if (submitted) {
    return <div className={_cn}>
        <Star size={16} fill="var(--color-success500, #22C55E)" color="var(--color-success500, #22C55E)" />
        <span className={_cn2}>Thanks! You rated this {selected}/5</span>
      </div>;
  }
  return <div className={_cn3}>
      <span className={_cn4}>Rate This Route</span>
      <div className={_cn5}>
        {[1, 2, 3, 4, 5].map(star => <XStack key={star} cursor={isSubmitting ? 'default' : 'pointer'} onPress={() => handleRate(star)} padding="$1" borderRadius="$2"
      // @ts-ignore — web-only mouse events
      onMouseEnter={() => !isSubmitting && setHovered(star)} onMouseLeave={() => setHovered(0)}>
            <Star size={28} fill={star <= active ? '#FF8C00' : 'transparent'} color={star <= active ? '#FF8C00' : 'var(--color-mutedForeground)'} strokeWidth={1.5} />
          </XStack>)}
        {isSubmitting && <span className={_cn6}>Saving...</span>}
      </div>
    </div>;
}

