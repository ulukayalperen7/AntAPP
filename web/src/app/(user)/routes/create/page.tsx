import { useState, useTransition } from 'react';
import { useRouter } from 'next/navigation';
import { YStack, XStack, Text, Button, Input } from '@antapp/ui';
import { createRoute } from '@/features/routes/actions';
import { ArrowLeft, Plus, Trash2 } from 'lucide-react';
type StopEntry = {
  id: string;
  spotId: string;
  customTitle: string;
  customDescription: string;
};
function generateTempId() {
  return Math.random().toString(36).slice(2);
}
export default function CreateRoutePage() {
  const router = useRouter();
  const [isPending, startTransition] = useTransition();
  const [title, setTitle] = useState('');
  const [description, setDescription] = useState('');
  const [stops, setStops] = useState<StopEntry[]>([{
    id: generateTempId(),
    spotId: '',
    customTitle: '',
    customDescription: ''
  }, {
    id: generateTempId(),
    spotId: '',
    customTitle: '',
    customDescription: ''
  }]);
  const [error, setError] = useState<string | null>(null);
  const addStop = () => {
    setStops(prev => [...prev, {
      id: generateTempId(),
      spotId: '',
      customTitle: '',
      customDescription: ''
    }]);
  };
  const removeStop = (id: string) => {
    setStops(prev => prev.filter(s => s.id !== id));
  };
  const updateStop = (id: string, field: keyof Omit<StopEntry, 'id'>, value: string) => {
    setStops(prev => prev.map(s => s.id === id ? {
      ...s,
      [field]: value
    } : s));
  };
  const handleSubmit = () => {
    setError(null);
    if (!title.trim()) {
      setError('Route title is required.');
      return;
    }
    const validStops = stops.filter(s => s.spotId.trim());
    if (validStops.length < 2) {
      setError('A route must have at least 2 spots with valid Spot IDs.');
      return;
    }
    startTransition(async () => {
      try {
        const routeId = await createRoute({
          title: title.trim(),
          description: description.trim() || undefined,
          spots: validStops.map(s => ({
            spotId: s.spotId.trim(),
            customTitle: s.customTitle.trim() || undefined,
            customDescription: s.customDescription.trim() || undefined
          }))
        });
        router.push(`/routes/${routeId}`);
      } catch (e) {
        setError((e as Error).message ?? 'Failed to create route.');
      }
    });
  };
  return <div className={_cn}>
      {/* Header */}
      <div className={_cn2}>
        <div className={_cn3} onClick={() => router.back()}>
          <ArrowLeft size={20} color="currentColor" />
        </div>
        <div className={_cn4}>
          <span className={_cn5}>Create Route</span>
          <span className={_cn6}>Build your adventure</span>
        </div>
      </div>

      {/* Route Info */}
      <div className={_cn7}>
        <span className={_cn8}>Route Information</span>

        <div className={_cn9}>
          <span className={_cn0}>Title *</span>
          <Input value={title} onChangeText={setTitle} variant="outline" size="md" placeholder="e.g. Classic Kaleici History Tour" />
        </div>

        <div className={_cn1}>
          <span className={_cn10}>Description</span>
          <Input value={description} onChangeText={setDescription} variant="outline" size="md" placeholder="Describe your route..."
        // @ts-ignore — multiline works on web
        multiline numberOfLines={3} />
        </div>
      </div>

      {/* Route Stops */}
      <div className={_cn11}>
        <div className={_cn12}>
          <div className={_cn13}>
            <span className={_cn14}>Route Stops</span>
            <span className={_cn15}>Add at least 2 stops (enter Spot IDs from the system)</span>
          </div>
          <Button variant="outline" size="sm" icon={<Plus size={14} color="currentColor" />} onPress={addStop}>
            Add Stop
          </Button>
        </div>

        <div className={_cn16}>
          {stops.map((stop, idx) => <div className={_cn17} key={stop.id}>
              {/* Step number */}
              <div className={_cn18}>
                <div className={!stop.spotId ? _cn19 : stop.spotId ? _cn20 : _cn21}>
                  <span className={!stop.spotId ? _cn22 : stop.spotId ? _cn23 : _cn24}>
                    {idx + 1}
                  </span>
                </div>
                {idx < stops.length - 1 && <div className={_cn25} />}
              </div>

              {/* Stop fields */}
              <div className={_cn26}>
                <div className={_cn27}>
                  <span className={_cn28}>Spot ID *</span>
                  <Input value={stop.spotId} onChangeText={v => updateStop(stop.id, 'spotId', v)} variant="outline" size="md" placeholder="Paste Spot UUID..." autoCapitalize="none" />
                </div>
                <div className={_cn29}>
                  <div className={_cn30}>
                    <span className={_cn31}>Custom Title (optional)</span>
                    <Input value={stop.customTitle} onChangeText={v => updateStop(stop.id, 'customTitle', v)} variant="outline" size="md" placeholder="Override spot name..." />
                  </div>
                </div>
              </div>

              {/* Remove */}
              {stops.length > 2 && <div className={_cn32} onClick={() => removeStop(stop.id)}>
                  <Trash2 size={16} color="var(--color-error500, #DC2626)" />
                </div>}
            </div>)}
        </div>
      </div>

      {/* Error */}
      {error && <div className={_cn33}>
          <span className={_cn34}>{error}</span>
        </div>}

      {/* Footer Actions */}
      <div className={_cn35}>
        <Button variant="outline" size="md" onPress={() => router.back()}>
          Cancel
        </Button>
        <Button variant="solid" size="md" loading={isPending} disabled={isPending || !title.trim()} onPress={handleSubmit} flex={1}>
          Create Route
        </Button>
      </div>
    </div>;
}