import { ArrowLeft, MapPinned, Route as RouteIcon, Star } from 'lucide-react';
function routeToCardData(route: SpotRouteItem): RouteCardData {
  return {
    id: route.id,
    title: route.title,
    description: route.description ?? undefined,
    image: route.thumbnailUrl ?? undefined,
    rating: route.averageRating > 0 ? route.averageRating : undefined
  };
}
function SpotRatingWidget({
  spotId,
  onRated
}: {
  spotId: string;
  onRated: (score: number) => void;
}) {
  const [hovered, setHovered] = useState(0);
  const [selected, setSelected] = useState(0);
  const [submitted, setSubmitted] = useState(false);
  const [isPending, startTransition] = useTransition();
  const active = hovered || selected;
  const handleRate = (score: number) => {
    if (submitted) return;
    setSelected(score);
    startTransition(async () => {
      try {
        await rateSpot(spotId, score);
        setSubmitted(true);
        onRated(score);
      } catch {
        setSelected(0);
      }
    });
  };
  return <div className={_cn}>
      <span className={_cn2}>Rate this spot</span>
      <div className={_cn3}>
        {[1, 2, 3, 4, 5].map(score => <XStack key={score} padding="$1" borderRadius="$2" cursor={submitted || isPending ? 'default' : 'pointer'} onPress={() => handleRate(score)}
      // @ts-ignore web-only mouse handlers
      onMouseEnter={() => !submitted && !isPending && setHovered(score)} onMouseLeave={() => setHovered(0)}>
            <Star size={26} fill={score <= active ? '#FF8C00' : 'transparent'} color={score <= active ? '#FF8C00' : 'var(--color-mutedForeground)'} strokeWidth={1.5} />
          </XStack>)}
        {isPending && <span className={_cn4}>Saving...</span>}
      </div>
      {submitted && <div className={_cn5}>
          <span className={_cn6}>Thanks! You rated this spot {selected}/5.</span>
        </div>}
    </div>;
}
